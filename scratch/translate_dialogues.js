for (const [file, arList] of Object.entries(translations)) {
    if (!fs.existsSync(file)) {
        console.log('File not found:', file);
        continue;
    }
    const content = fs.readFileSync(file, 'utf8');
    global.window = {};
    eval(content);
    const d = global.window.lessonData || global.window.__LESSON_DATA__;
    if (d && d.dialogue && Array.isArray(d.dialogue.turns)) {
        d.dialogue.turns.forEach((t, i) => {
            if (arList[i]) {
                t.ar = arList[i];
            }
        });
        
        // Save back with proper formatting
        const newCode = 'window.lessonData = ' + JSON.stringify(d, null, 4) + ';\n';
        fs.writeFileSync(file, newCode, 'utf8');
        console.log('✅ Updated dialogue Arabic translations in:', file, `(${arList.length} turns)`);
    } else {
        console.log('No dialogue turns in:', file);
    }
}
